package client

import (
	"strings"
	"testing"
)

const optionsXML = `<protocol name="opt"><copyright>Copyright test
SPDX-License-Identifier: MIT</copyright><interface name="opt_thing" version="1"/></protocol>`

func generateOptions(t *testing.T, mutate func(*Scanner)) string {
	t.Helper()
	s := NewScanner()
	if err := s.Load([]byte(optionsXML), "opt.xml"); err != nil {
		t.Fatal(err)
	}
	if mutate != nil {
		mutate(s)
	}
	b, err := s.Generate("opt")
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestToolNameInHeader(t *testing.T) {
	if got := generateOptions(t, nil); !strings.HasPrefix(got, "// Code generated by wlbgen. DO NOT EDIT.\n") {
		t.Fatalf("default header: %q", strings.SplitN(got, "\n", 2)[0])
	}
	got := generateOptions(t, func(s *Scanner) { s.Tool = "wlturbo-scanner" })
	if !strings.HasPrefix(got, "// Code generated by wlturbo-scanner. DO NOT EDIT.\n") {
		t.Fatalf("custom header: %q", strings.SplitN(got, "\n", 2)[0])
	}
}

func TestSPDXLineOnlyWhenRequested(t *testing.T) {
	const line = "// SPDX-License-Identifier: LGPL-2.1-or-later\n"
	if got := generateOptions(t, nil); strings.Contains(got, line) {
		t.Fatal("SPDX line emitted without request")
	}
	got := generateOptions(t, func(s *Scanner) { s.SPDXLicense = "LGPL-2.1-or-later" })
	header, _, _ := strings.Cut(got, "\npackage opt")
	if strings.Count(header, line) != 1 || !strings.Contains(header, "// Copyright test") {
		t.Fatalf("header: %s", header)
	}
}

func TestSPDXNotDuplicatedWhenCopyrightHasIt(t *testing.T) {
	got := generateOptions(t, func(s *Scanner) { s.SPDXLicense = "MIT" })
	if n := strings.Count(got, "SPDX-License-Identifier: MIT"); n != 1 {
		t.Fatalf("SPDX line count = %d", n)
	}
}

func TestCoreDetectionFollowsWlDisplay(t *testing.T) {
	const xml = `<protocol name="x"><interface name="wl_display" version="1"/><interface name="wl_registry" version="1"/><interface name="wl_thing" version="1"/></protocol>`
	for _, pkg := range []string{"wayland", "core", "anything"} {
		s := NewScanner()
		if err := s.Load([]byte(xml), "x.xml"); err != nil {
			t.Fatal(err)
		}
		b, err := s.Generate(pkg)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(b), "type Display struct") || strings.Contains(string(b), "type Registry struct") || !strings.Contains(string(b), "type Thing struct") {
			t.Fatalf("package %s: bootstrap types not skipped", pkg)
		}
	}
	// A package named "core" that does not define wl_display is not core.
	s := NewScanner()
	if err := s.Load([]byte(`<protocol name="x"><interface name="wl_registry" version="1"/></protocol>`), "x.xml"); err != nil {
		t.Fatal(err)
	}
	b, err := s.Generate("core")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "type Registry struct") {
		t.Fatal("core name alone must not trigger core handling")
	}
}
