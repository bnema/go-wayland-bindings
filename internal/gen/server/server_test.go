package server

import (
	"strings"
	"testing"

	"github.com/bnema/go-wayland-bindings/spec"
)

func TestUntypedNewIDEvent(t *testing.T) {
	p := &spec.Protocol{Interfaces: []spec.Interface{{Name: "test_device", Version: 1, Events: []spec.Message{{Name: "created", Args: []spec.Arg{{Name: "id", Type: "new_id"}}}}}}}
	b, err := Generate(p, Options{Package: "test"})
	if err != nil {
		t.Fatal(err)
	}
	s := string(b)
	if !strings.HasPrefix(s, "// Code generated by wlbgen; DO NOT EDIT.\n") {
		t.Fatalf("unexpected header:\n%s", s)
	}
	if !strings.Contains(s, `Signature: "sun"`) || !strings.Contains(s, `server.String(&p, id.Iface().Name, false), server.Uint(uint32(id.Version())), server.NewID(id)`) {
		t.Fatalf("untyped new_id event missing wire args:\n%s", s)
	}
}

func TestToolHeader(t *testing.T) {
	p := &spec.Protocol{Interfaces: []spec.Interface{{Name: "test_device", Version: 1}}}
	b, err := Generate(p, Options{Package: "test", Tool: "wlgen"})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(b), "// Code generated by wlgen; DO NOT EDIT.\n") {
		t.Fatalf("unexpected header:\n%s", b)
	}
}

func TestUnknownInterface(t *testing.T) {
	p := &spec.Protocol{Interfaces: []spec.Interface{{Name: "a", Version: 1, Events: []spec.Message{{Name: "e", Args: []spec.Arg{{Name: "o", Type: "object", Interface: "missing"}}}}}}}
	if _, err := Generate(p, Options{Package: "test"}); err == nil {
		t.Fatal("expected error for unknown interface")
	}
}

func TestSignature(t *testing.T) {
	cases := []struct {
		m    spec.Message
		want string
	}{
		{spec.Message{Name: "bind", Args: []spec.Arg{{Type: "uint"}, {Type: "new_id"}}}, "usun"},
		{spec.Message{Since: 2, Args: []spec.Arg{{Type: "object", AllowNull: true}, {Type: "fd"}, {Type: "fixed"}}}, "2?ohf"},
		{spec.Message{Args: []spec.Arg{{Type: "new_id", Interface: "wl_surface"}}}, "n"},
	}
	for _, c := range cases {
		if got := signature(c.m); got != c.want {
			t.Errorf("signature(%+v)=%q, want %q", c.m, got, c.want)
		}
	}
}
